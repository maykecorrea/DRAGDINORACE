export type Lang = "pt" | "en";

const PORTUGUESE = new Set(["BR", "PT", "AO", "MZ", "CV", "GW", "ST", "TL"]);

export function countryToLang(code: string): Lang {
  return PORTUGUESE.has(code.toUpperCase()) ? "pt" : "en";
}

export function langFromAccept(header: string): Lang {
  const tags = header.split(",").map((part) => part.split(";")[0]?.trim().toLowerCase() ?? "");
  for (const tag of tags) {
    if (tag.startsWith("pt")) return "pt";
    if (tag.startsWith("en")) return "en";
  }
  return "pt";
}

export function isPrivateIp(ip: string): boolean {
  const v = ip.trim().toLowerCase().replace(/^::ffff:/, "");
  if (!v || v === "::1" || v.startsWith("127.") || v.startsWith("10.") || v.startsWith("192.168.") || v.startsWith("fe80:") || v.startsWith("fc") || v.startsWith("fd")) {
    return true;
  }
  return /^172\.(1[6-9]|2\d|3[0-1])\./.test(v);
}

